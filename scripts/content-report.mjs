#!/usr/bin/env node
/**
 * Lists what each artwork is still missing and writes docs/CONTENT-NEEDED.md.
 * Run with: npm run content:report
 */
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = new URL('..', import.meta.url).pathname;
const WORKS = join(ROOT, 'src/content/works');

/** Minimal front-matter reader: `key: value` lines plus the body after the closing ---. */
function read(slug) {
  const raw = readFileSync(join(WORKS, slug, 'index.md'), 'utf8');
  const [, fm = '', body = ''] = raw.match(/^---\n([\s\S]*?)\n---\n?([\s\S]*)$/) ?? [];
  const data = {};
  for (const line of fm.split('\n')) {
    const m = line.match(/^(\w+):\s*(.*)$/);
    if (m) data[m[1]] = m[2].trim();
  }
  return { slug, data, body: body.trim() };
}

const works = readdirSync(WORKS, { withFileTypes: true })
  .filter((d) => d.isDirectory() && existsSync(join(WORKS, d.name, 'index.md')))
  .map((d) => read(d.name))
  .sort((a, b) => Number(a.data.order ?? 1000) - Number(b.data.order ?? 1000));

const rows = works.map((w) => {
  const d = w.data;
  const missing = [];
  if (!d.title) missing.push('title');
  if (!d.width || !d.height) missing.push('size');
  if (!d.medium) missing.push('medium');
  if (!d.year) missing.push('year');
  if (d.status === 'inquire') missing.push('status');
  if (d.status === 'available' && !d.price) missing.push('price (or keep "on request")');
  if (!w.body) missing.push('statement');
  return { ...w, missing };
});

const complete = rows.filter((r) => r.missing.length === 0).length;
const line = (r) =>
  `| \`${r.slug}\` | ${r.data.title ?? '—'} | ${r.data.status ?? 'inquire'} | ${r.data.collections ?? ''} | ${r.missing.join(', ') || '✓'} |`;

const md = `# Content needed

*Generated by \`npm run content:report\` — re-run after editing works.*

**${works.length} works · ${complete} complete.** Each work lives in \`src/content/works/<folder>/index.md\`.
Fill in what you know; anything left blank is simply not shown on the site (no placeholders).

## Site-wide

- [ ] **About — biography:** v1 had "Trained in [discipline] at [school], he came to casting through [route] and has been
      pouring since [year]." The sentence is removed until you supply the facts.
- [ ] **About — exhibitions and press:** v1 listed only placeholders, so the section is hidden. Send real shows, venues, years
      and any press to bring it back.
- [ ] **Collection descriptions:** Figurative and Sculptural were placeholders in v1; Claude drafted one line each in
      \`src/lib/site.ts\` — approve or rewrite.
- [ ] **Collections assigned by eye:** the 12 v1 "Available" works and 6 "reference" works had no collection; Claude
      assigned one from the image. Check the \`collections:\` line of each.
- [ ] **Size direction:** v1 captions read as width × height (e.g. Rising Above, 24 × 36, is a tall piece). Confirm.
- [ ] **Lifted Up (48 × 72):** its only photo is a wide outdoor installation shot — send a straight-on photo of the piece.
- [ ] **Available No. 002** (now \`untitled-sculptural-08\`, sold) carried the same caption as No. 001 "Green Horizon,
      34 × 48" — real title and size?
- [ ] **Prices:** show prices on available works, or keep "Price on request"? Add \`price: 4800\` to a work to show it.
- [ ] **Assistant answers:** \`src/lib/faq.ts\` was drafted from the v1 site's own wording (process, lead time, delivery,
      trade, materials). Read it once — Ask AI repeats it to visitors. Add anything you'd like it to know (care,
      payment, shipping costs, show dates).
- [ ] **Featured works:** add \`featured: true\` to up to 8 works to choose what the home page shows.
- [ ] **Shows & fairs:** upcoming show dates would help art-fair visitors find you again.
- [ ] **Unused photos:** \`src/assets/site/hero-macro-2/3/6.webp\` look like finished works not in the catalogue — are they?

## Works

| Folder | Title | Status | Collections | Missing |
|---|---|---|---|---|
${rows.map(line).join('\n')}
`;

writeFileSync(join(ROOT, 'docs/CONTENT-NEEDED.md'), md);
console.log(`${works.length} works, ${complete} complete → docs/CONTENT-NEEDED.md`);
